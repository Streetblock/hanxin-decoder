function freezeBatch([count, dataCodewords, correctionCodewords]) {
  return Object.freeze({
    count,
    dataCodewords,
    correctionCodewords,
    totalCodewords: dataCodewords + correctionCodewords,
  });
}

function buildLevel(version, errorCorrectionLevel, rawBatches) {
  const batches = Object.freeze(rawBatches.map(freezeBatch));
  const blockCount = batches.reduce((sum, batch) => sum + batch.count, 0);
  const dataCodewords = batches.reduce(
    (sum, batch) => sum + batch.count * batch.dataCodewords,
    0,
  );
  const correctionCodewords = batches.reduce(
    (sum, batch) => sum + batch.count * batch.correctionCodewords,
    0,
  );

  return Object.freeze({
    version,
    dimension: dimensionForVersion(version),
    errorCorrectionLevel,
    blockCount,
    totalCodewords: dataCodewords + correctionCodewords,
    dataCodewords,
    correctionCodewords,
    dataBits: dataCodewords * 8,
    batches,
  });
}

export const HAN_XIN_RS_BLOCK_TABLE = Object.freeze(
  RAW_RS_BLOCKS.map((levels, versionIndex) => Object.freeze(
    levels.map((batches, errorCorrectionLevel) => (
      buildLevel(versionIndex + 1, errorCorrectionLevel, batches)
    )),
  )),
);

export function rsBlockStructureFor(version, errorCorrectionLevel) {
  if (!Number.isInteger(version)
    || version < MIN_HAN_XIN_VERSION
    || version > MAX_HAN_XIN_VERSION) {
    throw new RangeError(
      `Han Xin version must be an integer from ${MIN_HAN_XIN_VERSION} to ${MAX_HAN_XIN_VERSION}`,
    );
  }
  if (!Number.isInteger(errorCorrectionLevel)
    || errorCorrectionLevel < 0
    || errorCorrectionLevel > 3) {
    throw new RangeError("errorCorrectionLevel must be an integer from 0 to 3");
  }
  return HAN_XIN_RS_BLOCK_TABLE[version - 1][errorCorrectionLevel];
}

export function expandRsBlocks(version, errorCorrectionLevel) {
  const structure = rsBlockStructureFor(version, errorCorrectionLevel);
  const blocks = [];
  for (let batchIndex = 0; batchIndex < structure.batches.length; batchIndex += 1) {
    const batch = structure.batches[batchIndex];
    for (let blockIndex = 0; blockIndex < batch.count; blockIndex += 1) {
      blocks.push(Object.freeze({
        batchIndex,
        blockIndex,
        dataCodewords: batch.dataCodewords,
        correctionCodewords: batch.correctionCodewords,
        totalCodewords: batch.totalCodewords,
      }));
    }
  }
  return Object.freeze(blocks);
}

